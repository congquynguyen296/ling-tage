function createVariants(
  productId: number,
  sizes: string[],
  color: string,
  colorHex: string,
  price: number
) {
  return sizes.map((size, idx) => ({
    id: `var-${productId}-${size}`,
    sku: `TG-FW26-${String(productId).padStart(2, "0")}-${size}`,
    size,
    color,
    colorHex,
    // Keep realistic stock numbers (and 1 occasional low-stock size)
    stock: (productId + idx) % 7 === 0 ? 0 : 4 + ((productId * 3 + idx * 2) % 15),
    price,
  }));
}

